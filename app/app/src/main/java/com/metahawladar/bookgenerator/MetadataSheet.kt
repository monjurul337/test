package com.metahawladar.bookgenerator

import kotlin.math.roundToInt

/**
 * The upload sheet: every field the Google Play / KDP / Draft2Digital forms ask
 * for, in the order they ask for it.
 */
object MetadataSheet {

    fun build(plan: BookPlan, words: Int, chapterCount: Int, epubName: String): String {
        val pages = (words / 250.0).roundToInt()
        val b = StringBuilder()
        val rule = "-".repeat(66)

        fun field(label: String, value: String) {
            if (value.isBlank()) return
            b.appendLine(rule).appendLine(label).appendLine(wrap(value)).appendLine()
        }

        fun list(label: String, items: List<String>, numbered: Boolean) {
            if (items.isEmpty()) return
            b.appendLine(rule).appendLine(label)
            items.forEachIndexed { i, s ->
                b.appendLine(if (numbered) "  ${i + 1}. $s" else "  - $s")
            }
            b.appendLine()
        }

        b.appendLine("=".repeat(66))
            .appendLine("BOOK METADATA - ${plan.title}")
            .appendLine("Generated by Book Generator - Meta Hawladar Team")
            .appendLine("=".repeat(66))
            .appendLine()

        field("TITLE", plan.title)
        field("SUBTITLE", plan.subtitle)
        field("SERIES", plan.series)
        field("AUTHOR", plan.author)
        field("LANGUAGE", "English (en)")
        field("LENGTH", "$words words | $chapterCount chapters | about $pages pages")
        field("LIST PRICE", "USD %.2f".format(plan.priceUsd))
        field("MINIMUM AGE", "${plan.minAge}   (maximum age: leave blank)")
        field("FOR MATURE AUDIENCES", if (plan.mature) "Yes" else "No")
        field("APPLY DRM ENCRYPTION", "No")
        field("PREVIEW LIMIT", "20% (recommended)")
        field("COPY / PASTE LIMIT", "0%")
        field("ALLOW PRE-ORDERS", "No  -  switch to Yes only for book 2 or later in a series")
        field("RELEASE DATE", "About 10 days from today, so every store goes live together")
        field("PUBLICATION DATE", "Today")
        field("SHORT DESCRIPTION (under 400 characters)", plan.shortDescription)
        field("DESCRIPTION", plan.description)
        list("BISAC CATEGORIES (first one is the primary category)", plan.bisac, true)
        list("KEYWORDS (use every slot)", plan.keywords, true)
        field("TARGET READER", plan.targetReader)
        list("COMPARABLE TITLES", plan.compTitles, false)
        field("CONTRIBUTOR BIOGRAPHY (role: Author)", plan.authorBio)
        field("ISBN", "Leave blank - the distributor assigns a free ISBN.")

        b.appendLine(rule)
            .appendLine("FILES TO UPLOAD")
            .appendLine("  $epubName")
            .appendLine("  cover.png  (1600 x 2560)")
            .appendLine()
            .appendLine("=".repeat(66))
        return b.toString()
    }

    private fun wrap(text: String, width: Int = 78): String {
        val out = ArrayList<String>()
        for (para in text.split("\n")) {
            if (para.isBlank()) { out.add(""); continue }
            val line = StringBuilder()
            for (word in para.trim().split(Regex("\\s+"))) {
                when {
                    line.isEmpty() -> line.append(word)
                    line.length + 1 + word.length <= width -> line.append(' ').append(word)
                    else -> { out.add(line.toString()); line.clear(); line.append(word) }
                }
            }
            if (line.isNotEmpty()) out.add(line.toString())
        }
        return out.joinToString("\n")
    }
}
