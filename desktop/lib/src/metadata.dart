import 'plan.dart';

/// The upload sheet: every field the Google Play / KDP / Draft2Digital forms ask
/// for, in the order they ask for it.
class MetadataSheet {
  static String build({
    required BookPlan plan,
    required int words,
    required int chapterCount,
    required String epubName,
  }) {
    final int pages = (words / 250).round();
    final StringBuffer b = StringBuffer();
    void rule() => b.writeln('-' * 66);
    void field(String label, String value) {
      if (value.trim().isEmpty) return;
      rule();
      b..writeln(label)..writeln(_wrap(value))..writeln();
    }

    b
      ..writeln('=' * 66)
      ..writeln('BOOK METADATA - ${plan.title}')
      ..writeln('Generated by Book Generator - Meta Hawladar Team')
      ..writeln('=' * 66)
      ..writeln();

    field('TITLE', plan.title);
    field('SUBTITLE', plan.subtitle);
    field('SERIES', plan.series);
    field('AUTHOR', plan.author);
    field('LANGUAGE', 'English (en)');
    field('LENGTH',
        '$words words | $chapterCount chapters | about $pages pages');
    field('LIST PRICE', 'USD ${plan.priceUsd.toStringAsFixed(2)}');
    field('MINIMUM AGE', '${plan.minAge}   (maximum age: leave blank)');
    field('FOR MATURE AUDIENCES', plan.mature ? 'Yes' : 'No');
    field('APPLY DRM ENCRYPTION', 'No');
    field('PREVIEW LIMIT', '20% (recommended)');
    field('COPY / PASTE LIMIT', '0%');
    field('ALLOW PRE-ORDERS',
        'No  -  switch to Yes only for book 2 or later in a series');
    field('RELEASE DATE',
        'About 10 days from today, so every store goes live together');
    field('PUBLICATION DATE', 'Today');
    field('SHORT DESCRIPTION (under 400 characters)', plan.shortDescription);
    field('DESCRIPTION', plan.description);
    if (plan.bisac.isNotEmpty) {
      rule();
      b.writeln('BISAC CATEGORIES (first one is the primary category)');
      for (int i = 0; i < plan.bisac.length; i++) {
        b.writeln('  ${i + 1}. ${plan.bisac[i]}');
      }
      b.writeln();
    }
    if (plan.keywords.isNotEmpty) {
      rule();
      b.writeln('KEYWORDS (use every slot)');
      for (int i = 0; i < plan.keywords.length; i++) {
        b.writeln('  ${i + 1}. ${plan.keywords[i]}');
      }
      b.writeln();
    }
    field('TARGET READER', plan.targetReader);
    if (plan.compTitles.isNotEmpty) {
      rule();
      b.writeln('COMPARABLE TITLES');
      for (final String c in plan.compTitles) {
        b.writeln('  - $c');
      }
      b.writeln();
    }
    field('CONTRIBUTOR BIOGRAPHY (role: Author)', plan.authorBio);
    field('ISBN', 'Leave blank - the distributor assigns a free ISBN.');
    rule();
    b
      ..writeln('FILES TO UPLOAD')
      ..writeln('  $epubName')
      ..writeln('  cover.png  (1600 x 2560)')
      ..writeln()
      ..writeln('=' * 66);
    return b.toString();
  }

  static String _wrap(String text, [int width = 78]) {
    final List<String> out = <String>[];
    for (final String para in text.split('\n')) {
      if (para.trim().isEmpty) {
        out.add('');
        continue;
      }
      final StringBuffer line = StringBuffer();
      for (final String word in para.trim().split(RegExp(r'\s+'))) {
        if (line.isEmpty) {
          line.write(word);
        } else if (line.length + 1 + word.length <= width) {
          line.write(' $word');
        } else {
          out.add(line.toString());
          line
            ..clear()
            ..write(word);
        }
      }
      if (line.isNotEmpty) out.add(line.toString());
    }
    return out.join('\n');
  }
}
